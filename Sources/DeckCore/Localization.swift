/// Language selection is saved in Rust settings; the lock permits background menu reads.
public final class DeckLanguage: @unchecked Sendable {
    public static let shared = DeckLanguage()
    private let lock = NSLock()
    private var selection: String?
    private init() {}
    public func set(_ value: String?) {
        lock.lock(); defer { lock.unlock() }
        selection = value
    }
    public var isEnglish: Bool {
        lock.lock(); let current = selection; lock.unlock()
        return (current ?? (Locale.preferredLanguages.first?.lowercased().hasPrefix("ko") == true ? "ko" : "en")) == "en"
    }
}
public func L(_ key: String) -> String {
    DeckLanguage.shared.isEnglish ? (englishTranslations[key] ?? key) : key
}
public func L(_ key: String, _ arguments: CVarArg...) -> String {
    String(format: L(key), locale: Locale(identifier: DeckLanguage.shared.isEnglish ? "en" : "ko"), arguments: arguments)
}
